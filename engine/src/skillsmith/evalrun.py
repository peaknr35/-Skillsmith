"""Eval harness: run the stage-06 tests against a real model.

Part A, trigger test: the model sees only skill names and descriptions (the real skill plus
distractors) and picks one or none for each should-fire / near-miss prompt.
Part B, task comparison: each task is answered twice, without the skill and with SKILL.md in
the system prompt. Raw outputs are saved for a human to read side by side. Two automatic
signals are added: marker counts (deterministic) and a blind LLM judge over the expected
differences (a screen, not proof).

Honest limits, repeated in every report: one sample per prompt, one model, the tests were
generated by the same model that helped build the skill, and the judge is an LLM."""
from __future__ import annotations

import json
import random
import re
import time
from datetime import datetime, timezone
from pathlib import Path

from .runner import StageError, extract_json
from .schema import EvalSet, EvalTask
from .workspace import Workspace

BASELINE_SYSTEM = "You are a helpful assistant."

DEFAULT_DISTRACTORS = [
    ("python-async-task-runner", "Use when scheduling concurrent Python async tasks and background queues."),
    ("git-workflow-automator", "Use when configuring automated git hooks, branching strategies and PR checks."),
    ("llm-prompt-compressor", "Use when applying prompt compression algorithms to reduce context length."),
]


class EvalRunError(Exception):
    pass


def _call(provider, system: str, user: str, tries: int = 4) -> str:
    """Provider call with backoff for transient network errors; a clean error if it stays down."""
    last: Exception | None = None
    for i in range(tries):
        try:
            return provider.complete(system, user)
        except Exception as e:  # SDK/network errors vary by provider
            if type(e).__name__ == "TruncatedOutput":
                raise EvalRunError(str(e)) from e
            last = e
            if i + 1 < tries:
                time.sleep(min(2 ** i * 2, 15))
    raise EvalRunError(f"provider call failed after {tries} attempts: {type(last).__name__}: {last}")


def load_eval(w: Workspace, skill: str) -> EvalSet:
    f = w.output("06_eval") / "evals" / skill / "eval.json"
    if not f.is_file():
        raise EvalRunError(f"{f} not found; run stage 06 first")
    return EvalSet.model_validate_json(f.read_text(encoding="utf-8"))


def load_distractors(w: Workspace) -> list[tuple[str, str]]:
    f = w.root / "_config" / "eval-distractors.json"
    if f.is_file():
        return [(d["name"], d["description"]) for d in json.loads(f.read_text(encoding="utf-8"))]
    return DEFAULT_DISTRACTORS


# ------------------------------------------------------------------ Part A
def trigger_test(provider, name: str, description: str, es: EvalSet,
                 distractors: list[tuple[str, str]], seed: int = 0) -> dict:
    skills = [(name, description), *distractors]
    random.Random(seed).shuffle(skills)  # position of the real skill must not matter
    system = ("You route user requests to skills. Available skills:\n"
              + "\n".join(f"- {n}: {d}" for n, d in skills)
              + '\nChoose the single skill whose description matches the request, or none. '
                'Reply with ONLY JSON: {"selected_skill": "<skill name or none>"}.')
    rows = []
    for expected, prompts in ((True, es.should_fire), (False, es.should_not_fire)):
        for p in prompts:
            raw = _call(provider, system, p)
            try:
                sel = str(extract_json(raw).get("selected_skill", "none")).strip()
            except (ValueError, AttributeError):
                sel = "invalid"
            picked = sel == name
            rows.append({"prompt": p, "expected_fire": expected, "selected": sel, "fired": picked,
                         "ok": picked == expected, "distractor_picked": sel in {d[0] for d in distractors}})
    pos = [r for r in rows if r["expected_fire"]]
    neg = [r for r in rows if not r["expected_fire"]]
    return {"rows": rows, "recall": sum(r["fired"] for r in pos) / len(pos),
            "false_positives": sum(r["fired"] for r in neg), "n_pos": len(pos), "n_neg": len(neg),
            "invalid": sum(r["selected"] == "invalid" for r in rows)}


# ------------------------------------------------------------------ Part B
def _count(markers: list[str], text: str) -> dict:
    low = text.lower()
    hits = {m: (m.lower() in low) for m in markers}
    return {"hit": sum(hits.values()), "total": len(markers), "which": hits}


def judge(provider, task: EvalTask, out_a: str, out_b: str) -> dict:
    """Blind: the judge sees Option 1 and Option 2 only, never which one had the skill.
    Scores both individual pass count and strict completion (all items pass simultaneously;
    SkillForgeBench arXiv 2610.14918 found 70-85.7% individual vs 12.6-40.9% strict)."""
    items = list(task.expected_differences) + [f"[process] {p}" for p in task.process_checks]
    system = ("You are a strict, literal evaluator. For each listed behaviour, say whether each option "
              "clearly exhibits it. Judge only what is written. Reply with ONLY JSON: "
              '{"per_behaviour": [{"behaviour": "...", "option1": true|false, "option2": true|false}]}')
    user = (f"User request:\n{task.prompt}\n\nBehaviours to check:\n"
            + "\n".join(f"{i + 1}. {b}" for i, b in enumerate(items))
            + f"\n\n=== Option 1 ===\n{out_a}\n\n=== Option 2 ===\n{out_b}\n")
    raw = _call(provider, system, user)
    try:
        data = extract_json(raw)
        rows = data["per_behaviour"]
        o1 = sum(bool(r.get("option1")) for r in rows)
        o2 = sum(bool(r.get("option2")) for r in rows)
        n = len(items)
        return {"o1": o1, "o2": o2, "n": n, "strict_o1": bool(rows) and o1 == n,
                "strict_o2": bool(rows) and o2 == n, "rows": rows}
    except (ValueError, KeyError, TypeError):
        return {"o1": None, "o2": None, "n": len(items), "strict_o1": False, "strict_o2": False,
                "rows": [], "error": raw[:200]}


def task_comparison(provider, skill_dir: Path, es: EvalSet, out_dir: Path,
                    with_playbook: bool = False, seed: int = 0) -> list[dict]:
    skill_md = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    if with_playbook:
        skill_md += "\n\n" + (skill_dir / "playbook.md").read_text(encoding="utf-8")
    treatment_system = (BASELINE_SYSTEM + "\n\nA skill is loaded for this conversation. Apply it when the "
                        "request falls within its description.\n\n" + skill_md)
    rng = random.Random(seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    results = []
    for i, t in enumerate(es.tasks, 1):
        base = _call(provider, BASELINE_SYSTEM, t.prompt)
        treat = _call(provider, treatment_system, t.prompt)
        (out_dir / f"task_{i:02d}_baseline.md").write_text(f"# Task {i} baseline (no skill)\n\n{t.prompt}\n\n---\n\n{base}\n", encoding="utf-8")
        (out_dir / f"task_{i:02d}_treatment.md").write_text(f"# Task {i} treatment (skill loaded)\n\n{t.prompt}\n\n---\n\n{treat}\n", encoding="utf-8")
        swap = rng.random() < 0.5  # which output is shown as Option 1
        j = judge(provider, t, treat if swap else base, base if swap else treat)
        score = {"baseline": j["o2"] if swap else j["o1"], "treatment": j["o1"] if swap else j["o2"],
                 "strict_baseline": j["strict_o2"] if swap else j["strict_o1"],
                 "strict_treatment": j["strict_o1"] if swap else j["strict_o2"]}
        tm_treat = _count(t.treatment_markers, treat)
        # If expect_apply is False (a nearby problem the skill does not fit), imposing the skill's
        # signature vocabulary in the answer is an over-application failure.
        over_applied = (not t.expect_apply) and tm_treat["hit"] >= max(2, (tm_treat["total"] + 1) // 2)
        results.append({"task": i, "neutral": t.neutral, "expect_apply": t.expect_apply, "prompt": t.prompt,
                        "over_applied": over_applied,
                        "baseline_markers": _count(t.baseline_markers, base) | {"in_treatment": _count(t.baseline_markers, treat)["hit"]},
                        "treatment_markers": tm_treat | {"in_baseline": _count(t.treatment_markers, base)["hit"]},
                        "judge": {"n": j["n"], **score, "blind_order_treatment_first": swap, "rows": j["rows"]},
                        "baseline_chars": len(base), "treatment_chars": len(treat)})
    return results


# ------------------------------------------------------------------ report
def render_report(skill: str, model: str, trig: dict, tasks: list[dict], with_playbook: bool) -> str:
    L = [f"# Eval run: {skill}", "", f"Model: {model}. Treatment context: SKILL.md{' + playbook.md' if with_playbook else ' only'}.", "",
         "> Limits: one sample per prompt, one model; the tests were generated by the same model family that helped build "
         "the skill; the judge is an LLM (a screen, not proof). Read the saved side-by-side outputs before concluding anything.", "",
         "## A. Trigger test (names and descriptions only, with 3 distractor skills)", "",
         f"- Recall on should-fire prompts: **{trig['recall']:.0%}** ({round(trig['recall'] * trig['n_pos'])}/{trig['n_pos']})",
         f"- False positives on near-miss prompts: **{trig['false_positives']}** of {trig['n_neg']}",
         f"- Unparseable replies: {trig['invalid']}", ""]
    for r in trig["rows"]:
        if not r["ok"]:
            L.append(f"- MISS ({'should fire' if r['expected_fire'] else 'should NOT fire'}; picked {r['selected']}): {r['prompt'][:140]}")
    strict_b = sum(bool(r["judge"].get("strict_baseline")) for r in tasks)
    strict_t = sum(bool(r["judge"].get("strict_treatment")) for r in tasks)
    over = [r["task"] for r in tasks if r.get("over_applied")]
    L += ["", "## B. Task comparison (without vs with the skill)", "",
          f"- Strict completion (all rubric items pass on a task): without skill **{strict_b}/{len(tasks)}**, "
          f"with skill **{strict_t}/{len(tasks)}**",
          f"- Near-miss over-application (expect_apply=false but skill markers imposed): "
          f"{'none' if not over else 'tasks ' + ', '.join(map(str, over))}", "",
          "| task | neutral | should apply | treatment markers: with / without skill | baseline markers: without / with skill | judge: without / with (of n) | strict: without / with |",
          "|---|---|---|---|---|---|---|"]
    for r in tasks:
        tm, bm, jd = r["treatment_markers"], r["baseline_markers"], r["judge"]
        sb = "yes" if jd.get("strict_baseline") else "no"
        st = "yes" if jd.get("strict_treatment") else "no"
        L.append(f"| {r['task']} | {'yes' if r['neutral'] else 'no'} | {'yes' if r.get('expect_apply', True) else 'no'} | "
                 f"{tm['hit']}/{tm['total']} / {tm['in_baseline']} | "
                 f"{bm['hit']}/{bm['total']} / {bm['in_treatment']} | {jd['baseline']} / {jd['treatment']} of {jd['n']} | {sb} / {st} |")
    L += ["", "Outputs: `task_NN_baseline.md` and `task_NN_treatment.md` in this folder.", ""]
    return "\n".join(L)


def run(w: Workspace, provider, skill: str | None = None, model: str = "", with_playbook: bool = False,
        parts: str = "both") -> Path:
    if not w.done("06_eval"):
        raise EvalRunError("stage 06_eval is not done")
    dirs = w.skill_dirs()
    d = next((x for x in dirs if skill in (None, x.name)), None)
    if d is None:
        raise EvalRunError(f"skill {skill!r} not found; have {[x.name for x in dirs]}")
    es = load_eval(w, d.name)
    spec_tool = json.loads((d / "tool.json").read_text(encoding="utf-8"))
    run_dir = w.stage_dir("06_eval") / "runs" / d.name / datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_dir.mkdir(parents=True, exist_ok=True)
    trig = {"rows": [], "recall": 0.0, "false_positives": 0, "n_pos": len(es.should_fire), "n_neg": len(es.should_not_fire), "invalid": 0}
    tasks: list[dict] = []
    try:
        if parts in ("both", "triggers"):
            trig = trigger_test(provider, spec_tool["name"], spec_tool["description"], es, load_distractors(w))
        if parts in ("both", "tasks"):
            tasks = task_comparison(provider, d, es, run_dir, with_playbook)
    except StageError:
        raise
    (run_dir / "results.json").write_text(json.dumps({"trigger": trig, "tasks": tasks}, indent=2), encoding="utf-8")
    (run_dir / "report.md").write_text(render_report(d.name, model, trig, tasks, with_playbook), encoding="utf-8")
    return run_dir
